#!/usr/bin/env python3
"""Generate crates/tarn-sql/src/collation_data.rs: the weight tables of the
case-insensitive collations Tarn implements, read from a MariaDB 10.11
server's WEIGHT_STRING() (the reference for Tarn's SQL behaviour).

    scripts/gen_collations.py [--host 127.0.0.1] [--port 3407] [--user sb] [--check]

utf8mb4_general_ci gives every BMP code point one 16-bit weight; the table
keeps the code points whose weight is not the code point itself.
utf8mb4_unicode_ci (UCA 4.0.0) gives each code point a sequence of primary
weights; CJK ideographs and unassigned code points get "implicit" weights
computed from the code point (see collation.rs), the rest are listed.
Both collations weigh every code point above U+FFFF 0xFFFD; the script
checks that and the implicit-weight rule against the server. --check
compares the file in the tree with what the server gives instead of
writing it.
"""
import argparse
import os
import sys

import pymysql

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "crates", "tarn-sql", "src", "collation_data.rs")

# Compatibility ideographs that UCA 4.0.0 weighs like unified ideographs.
FB40_EXTRA = [0xFA0E, 0xFA0F, 0xFA11, 0xFA13, 0xFA14, 0xFA1F, 0xFA21, 0xFA23, 0xFA24, 0xFA27, 0xFA28, 0xFA29]


def implicit(cp):
    """UCA 4.0.0 implicit primary weights, as MariaDB's utf8mb4_unicode_ci."""
    if 0x4E00 <= cp <= 0x9FA5 or cp in FB40_EXTRA:
        base = 0xFB40
    elif 0x3400 <= cp <= 0x4DB5:
        base = 0xFB80
    else:
        base = 0xFBC0
    return [base + (cp >> 15), (cp & 0x7FFF) | 0x8000]


def weights(cur, coll, cps):
    out = {}
    for i in range(0, len(cps), 1000):
        chunk = cps[i:i + 1000]
        cols = ",".join(f"HEX(WEIGHT_STRING(_utf8mb4 X'{chr(cp).encode().hex()}' COLLATE {coll}))" for cp in chunk)
        cur.execute("SELECT " + cols)
        for cp, h in zip(chunk, cur.fetchone()):
            out[cp] = [int(h[j:j + 4], 16) for j in range(0, len(h), 4)]
    return out


def rows(items, per_line):
    lines = []
    for i in range(0, len(items), per_line):
        lines.append("    " + " ".join(items[i:i + per_line]))
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, default=3407)
    ap.add_argument("--user", default="sb")
    ap.add_argument("--password", default="")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    conn = pymysql.connect(host=a.host, port=a.port, user=a.user, password=a.password, charset="utf8mb4")
    cur = conn.cursor()
    cur.execute("SELECT VERSION()")
    version = cur.fetchone()[0].split("-")[0]
    bmp = [cp for cp in range(0x10000) if not 0xD800 <= cp <= 0xDFFF]

    general = weights(cur, "utf8mb4_general_ci", bmp)
    gen_exc = []
    for cp in bmp:
        w = general[cp]
        if len(w) != 1:
            sys.exit(f"utf8mb4_general_ci: U+{cp:04X} has {len(w)} weights")
        if w[0] != cp:
            gen_exc.append((cp, w[0]))

    unicode = weights(cur, "utf8mb4_unicode_ci", bmp)
    index, flat = [], []
    for cp in bmp:
        w = unicode[cp]
        if w == implicit(cp):
            continue
        # (CJK radicals and compatibility ideographs carry the implicit
        # weights of the ideograph they stand for: listed.)
        index.append((cp, len(flat), len(w)))
        flat.extend(w)
    if len(flat) > 0xFFFF:
        sys.exit("weight array does not fit u16 offsets")

    supp = [0x10000, 0x1D400, 0x1F600, 0x20000, 0x10FFFF]
    for coll in ("utf8mb4_general_ci", "utf8mb4_unicode_ci"):
        for cp, w in weights(cur, coll, supp).items():
            if w != [0xFFFD]:
                sys.exit(f"{coll}: U+{cp:X} weighs {w}, expected 0xFFFD")

    text = f"""// Generated by scripts/gen_collations.py from the WEIGHT_STRING() of
// MariaDB {version}. Do not edit.

/// utf8mb4_general_ci: (code point, weight) for every BMP code point whose
/// weight is not the code point itself. Code points above U+FFFF weigh 0xFFFD.
pub static GENERAL_CI: [(u16, u16); {len(gen_exc)}] = [
{rows([f"(0x{c:04X}, 0x{w:04X})," for c, w in gen_exc], 6)}
];

/// utf8mb4_unicode_ci (UCA 4.0.0 primary weights): code points with listed
/// weights as (code point, offset, count) into `UNICODE_CI_WEIGHTS`; the
/// others have implicit weights. Code points above U+FFFF weigh 0xFFFD.
pub static UNICODE_CI_INDEX: [(u16, u16, u8); {len(index)}] = [
{rows([f"(0x{c:04X}, {o}, {n})," for c, o, n in index], 6)}
];

pub static UNICODE_CI_WEIGHTS: [u16; {len(flat)}] = [
{rows([f"0x{w:04X}," for w in flat], 12)}
];
"""
    if a.check:
        cur_text = open(OUT).read()
        if cur_text != text:
            sys.exit(f"{OUT} differs from what {version} gives")
        print(f"{OUT} matches {version}")
        return
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT}: {len(gen_exc)} general_ci exceptions, {len(index)} unicode_ci entries, "
          f"{len(flat)} weights (MariaDB {version})")


if __name__ == "__main__":
    main()
