#!/usr/bin/env python3
"""Validate the executable manifest and render its precise supported scope."""
import argparse
import ast
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def render(root=ROOT):
    m = json.loads((root / "contracts/manifest.json").read_text())
    assert m["schema"] == 1
    assert re.fullmatch(r"mysql:8\.4\.\d+@sha256:[0-9a-f]{64}", m["oracle"]["image"])
    entries = m["contracts"]
    ids = [e["id"] for e in entries]
    assert len(ids) == len(set(ids)), "duplicate contract ID"
    tree = ast.parse((root / "tests/sql/contracts.py").read_text())
    functions = {n.name[5:] for n in tree.body if isinstance(n, ast.FunctionDef) and n.name.startswith("case_")}
    assert functions == set(ids), f"unregistered/missing executable contracts: {functions ^ set(ids)}"
    lines = ["# Executable MySQL release contracts", "", "Generated by `scripts/check_contracts.py`; edit `contracts/manifest.json` and its tests together.", "", m["scope"], "",
             f"Primary InnoDB oracle: MySQL **{m['oracle']['version']}**, `{m['oracle']['image']}`.", "",
             "Connections pin `STRICT_TRANS_TABLES,NO_ENGINE_SUBSTITUTION`, `utf8mb4` / `utf8mb4_bin` and `+00:00`. Receipts retain the actual version, settings, client capability flags, protocol mode, manifest hash and every result/failure. These fixtures classify their explicit histories; they do not certify all SQL modes, collations or query shapes.", "",
             "| Contract/test ID | Classification | Guaranteed scope / observed difference |", "|---|---|---|"]
    for e in entries:
        assert e["classification"] in ("equivalent", "difference", "rejected"), e
        assert e["test"] == "tests/sql/contracts.py::case_" + e["id"], e
        assert e["description"] and "|" not in e["description"], e
        lines.append(f"| `{e['id']}` | {e['classification']} | {e['description']} |")
    lines += ["", "Each history runs with data statements sent as ordinary text and as binary prepared executions; settings and transaction control use text in both histories. `CLIENT_FOUND_ROWS` is checked in both modes. A registered equivalent case must match both servers and its explicit expected result. Difference/refusal cases assert each server's stated behavior rather than accepting any mismatch. A failed case remains in the result file and fails the job.", "",
              "The dedicated workflow runs native/Lua storage and memtx/vinyl RF3 clusters. The existing MariaDB differential, transaction, READ COMMITTED, storage, RF3/fault and formal CI remains required independently. No protocol, freshness, commit/locking/recovery action or verified body is changed by this reporting/contract work.", "",
              "## Isolation migration", "",
              "`@@transaction_isolation` remains the requested session default, including the legacy `REPEATABLE-READ` alias. `@@tarn_effective_isolation` exposes its actual default: `STRICT-SERIALIZABLE` for SERIALIZABLE/REPEATABLE READ, `READ-COMMITTED` for READ COMMITTED/READ UNCOMMITTED. `@@tarn_next_isolation` reports an unconsumed one-shot SET TRANSACTION setting or NULL. `@@tarn_active_isolation` reports the active transaction's effective mode or NULL; changing the session default does not change an active transaction.", "",
              "These Tarn diagnostics are read-only session variables. `@@global.transaction_isolation`, `@@global.innodb_lock_wait_timeout` and SHOW GLOBAL VARIABLES report gateway defaults independently of session overrides. Global defaults are gateway-local, not cluster-wide, and affect new connections only. Other GLOBAL assignments (including autocommit and sql_mode) are explicitly unsupported with 1235/42000; they do not alter session behavior or commit pending work.", "",
              "`SET SESSION tarn_isolation_contract='MYSQL'` refuses an exact MySQL-isolation request with 1235/42000, without committing or discarding buffered writes. `TARN` (also DEFAULT) acknowledges the documented contract. Clients migrating from the REPEATABLE READ alias should explicitly select SERIALIZABLE when they want Tarn's strong contract, and handle known 1213/40001 aborts. Applications requiring InnoDB's exact snapshot/current-read behavior cannot select it in this release. 1180/40003 remains outcome unknown and must not trigger automatic mutation replay.", "",
              "## Extending the gate", "",
              "Add a uniquely named `case_<id>` and matching manifest entry, with paired assertions for both outcomes and precise scope. Run `python3 scripts/check_contracts.py` and commit the generated page. `--check` rejects missing/duplicate/unregistered cases or stale generated documentation. Follow-ups for integrity declarations (#179), key/collation behavior (#180), strong KV (#181), lazy consistency (#182) and retry contracts (#183) extend this manifest; they are not implied complete by its initial entries.", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    path = ROOT / "docs/mysql-contracts.md"
    if args.check:
        assert path.read_text() == text, "run scripts/check_contracts.py and commit generated documentation"
    else:
        path.write_text(text)


if __name__ == "__main__":
    main()
