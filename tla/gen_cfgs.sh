mk () 
{ 
    local name=$1 rs=$2 ws=$3 fo=$4 cr=$5 lo=$6;
    shift 6;
    local RD=MCReaders AOP=FALSE ROV=FALSE RK=MCRKeys LRW=FALSE NRL=FALSE NWC=FALSE NTS=FALSE LIR=FALSE NRC=FALSE AMC=FALSE GC=FALSE BGD=FALSE BNE=FALSE BFE=FALSE INV="TypeOK AppliedOnlyIfCommitted NoAbortAfterCommit PlainOnlyCommitted DirectReadsClean DirectReadYourWrites StrictSerializable NoLostUpdate RCReadsSeeAcked UniqueHolds";
    local RCS=NoRC LS=NoLSet RNL=FALSE RIW=FALSE RRB=FALSE IPL=FALSE RIF=FALSE IK=NoIKeys INE=FALSE;
    for b in "$@";
    do
        case $b in 
            NRL)
                NRL=TRUE
            ;;
            NWC)
                NWC=TRUE
            ;;
            NTS)
                NTS=TRUE
            ;;
            LIR)
                LIR=TRUE
            ;;
            AOP)
                AOP=TRUE
            ;;
            RYW)
                INV="DirectReadYourWrites"
            ;;
            ATOMIC)
                INV="DirectReadAtomic"
            ;;
            LRW)
                LRW=TRUE
            ;;
            NRC)
                NRC=TRUE
            ;;
            ROV)
                ROV=TRUE
            ;;
            AMC)
                AMC=TRUE
            ;;
            GC)
                GC=TRUE; AMC=TRUE
            ;;
            BGD)
                BGD=TRUE
            ;;
            BNE)
                BNE=TRUE
            ;;
            BFE)
                BFE=TRUE
            ;;
            NORD)
                RD=NoReaders; RK=NoRKeys
            ;;
            RCC)
                RCS=RCCounter; LS=LSetCounter
            ;;
            RCM)
                RCS=RCMixed; LS=LSetMixed
            ;;
            RNL)
                RNL=TRUE
            ;;
            RIW)
                RIW=TRUE
            ;;
            RRB)
                RRB=TRUE
            ;;
            IPL)
                IPL=TRUE
            ;;
            RIF)
                RIF=TRUE
            ;;
            RCL)
                RCS=RCLocal; LS=LSetRCLocal
            ;;
            UNQ)
                IK=IKeysUniq
            ;;
            RCU)
                RCS=RCUniq; LS=LSetUniq
            ;;
            INE)
                INE=TRUE
            ;;
        esac;
    done;
    cat > $name.cfg <<EOF
\* generated by tla/gen_cfgs.sh
SPECIFICATION Spec
CONSTANTS
  Shards <- MCShards
  Keys <- MCKeys
  Owner <- MCOwner
  Txns <- MCTxns
  Readers <- $RD
  RKeys <- $RK
  RSet <- $rs
  WSet <- $ws
  MaxFailovers = $fo
  MaxCrashes = $cr
  MaxLoss = $lo
  MaxTimeouts = ${TO:-1}
  BugNoReadLocks = $NRL
  BugNoWLockCheckOnRead = $NWC
  BugNoTombstone = $NTS
  BugLocalIgnoresRLocks = $LIR
  AckOnPrepare = $AOP
  ROValidateOnly = $ROV
  BugLocalReadsIgnoreWLocks = $LRW
  BugROValidateNoReadCheck = $NRC
  ApplyMarksCommitted = $AMC
  GC = $GC
  BugGCIgnoresDecision = $BGD
  BugGCNoExpiry = $BNE
  BugFenceAfterExpiry = $BFE
  RC <- $RCS
  LSet <- $LS
  BugRCNoLockCheck = $RNL
  BugRCLockIgnoresWLocks = $RIW
  BugRCReadBeforeLock = $RRB
  BugIgnorePLocks = $IPL
  BugRCLockReadsInFlight = $RIF
  IKeys <- $IK
  BugInsertNoExistCheck = $INE
INVARIANTS $INV
CHECK_DEADLOCK FALSE
EOF

}
# The protocol as designed: every invariant must hold.
# Commit-phase faults (coordinator crash, message loss, recovery racing a
# live coordinator) on each workload:
mk Skew        RSetSkew  WSetSkew  0 1 1 NORD
mk Local       RSetLocal WSetLocal 0 1 1 NORD
mk Frac        RSetFrac  WSetFrac  0 1 1 NORD
mk Recov       RSetRecov WSetRecov 0 1 2 NORD
# Leader failover during execution, with a direct reader:
mk SkewFailover  RSetSkew  WSetSkew  1 0 0
mk LocalFailover RSetLocal WSetLocal 1 0 0
mk FracFailover  RSetFrac  WSetFrac  1 0 0
mk RecovReaders  RSetRecov WSetRecov 0 0 0
# AckOnPrepare (1 round-trip cross-shard commits) keeps SQL strict serializability:
mk Skew_AckOnPrepare  RSetSkew  WSetSkew  0 1 1 NORD AOP
mk Recov_AckOnPrepare RSetRecov WSetRecov 0 1 2 NORD AOP
# The implementation's commit paths: ROValidateOnly (cross-shard reads
# without PREPARE or locks) and ApplyMarksCommitted (the decision shard's
# APPLY records COMMITTED):
mk Skew_ROValidate      RSetSkew  WSetSkew  0 1 1 NORD ROV AMC
mk Frac_ROValidate      RSetFrac  WSetFrac  0 1 1 NORD ROV AMC
mk FracFailover_ROValidate RSetFrac WSetFrac 1 0 0 ROV AMC
mk Local_ROValidate     RSetLocal WSetLocal 0 1 1 NORD ROV AMC
mk LocalFailover_ROValidate RSetLocal WSetLocal 1 0 0 ROV AMC
mk SkewFailover_ROValidate  RSetSkew  WSetSkew  1 0 0 ROV AMC
# ... plus the record lifecycle: expiry and garbage collection of records
# (GC implies ApplyMarksCommitted):
mk Recov_GC             RSetRecov WSetRecov 0 1 2 NORD GC
mk Frac_GC_ROValidate   RSetFrac  WSetFrac  0 1 1 NORD ROV GC
mk Local_GC_ROValidate  RSetLocal WSetLocal 0 1 1 NORD ROV GC
mk Skew_GC_ROValidate   RSetSkew  WSetSkew  0 1 1 NORD ROV GC   # too large to finish: see out/Skew_GC_ROValidate.out
mk SkewTimeout_GC_ROValidate RSetSkew WSetSkew 0 0 0 NORD ROV GC   # recovery racing the coordinator, no crash/loss
# Each weakened variant must be caught.
mk Bug_NoReadLocks            RSetSkew  WSetSkew  0 0 0 NRL
mk Bug_LocalIgnoresRLocks     RSetLocal WSetLocal 0 0 0 LIR
mk Bug_NoWLockCheckOnRead     RSetFrac  WSetFrac  0 0 0 NWC
mk Bug_ROValidateNoWLockCheck RSetFrac  WSetFrac  0 0 0 ROV LRW
mk Bug_NoTombstone            RSetRecov WSetRecov 0 1 1 NTS
mk Bug_LocalReadsIgnoreWLocks RSetRecov WSetRecov 0 0 0 LRW
mk Bug_ROValidateNoReadCheck  RSetFrac  WSetFrac  0 0 0 ROV NRC
mk Bug_GCIgnoresDecision      RSetRecov WSetRecov 0 1 1 NORD GC BGD
mk Bug_GCNoExpiry             RSetRecov WSetRecov 0 1 1 NORD GC BNE
mk Bug_FenceAfterExpiry       RSetRecov WSetRecov 0 1 1 NORD GC BFE
# READ COMMITTED with pessimistic locks: RC read-modify-writes race each
# other and serializable transactions, through local commits and PREPARE/APPLY,
# under commit-phase faults and leader failovers (which empty the lock table).
mk RC_Counter          RSetCounter WSetCounter 0 1 1 NORD RCC AMC
mk RC_CounterFailover  RSetCounter WSetCounter 1 0 0 NORD RCC AMC
mk RC_Counter_AckOnPrepare RSetCounter WSetCounter 0 0 1 NORD RCC AMC AOP
mk RC_Mixed            RSetMixed   WSetMixed   0 1 1 NORD RCM AMC
mk RC_MixedFailover    RSetMixed   WSetMixed   1 0 0 RCM AMC
mk RC_Local            RSetRCLocal WSetRCLocal 0 1 1 NORD RCL AMC
mk Bug_RCNoLockCheck       RSetCounter WSetCounter 1 0 0 NORD RCC AMC RNL
mk Bug_RCLockIgnoresWLocks RSetCounter WSetCounter 0 0 0 NORD RCC AMC RIW
mk Bug_RCReadBeforeLock    RSetCounter WSetCounter 0 0 0 NORD RCC AMC RRB
mk Bug_IgnorePLocks        RSetCounter WSetCounter 0 0 0 NORD RCC AMC IPL
mk Bug_RCLockReadsInFlight RSetRCLocal WSetRCLocal 0 0 0 NORD RCL AMC RIF
# Unique keys without the shard key (issue #14): two rows with one value
# insert one global index entry, across shards and locally, under faults.
mk Uniq            RSetUniq WSetUniq 0 1 1 NORD UNQ AMC
mk UniqFailover    RSetUniq WSetUniq 1 0 0 UNQ AMC
mk Uniq_RC         RSetUniq WSetUniq 0 1 1 NORD UNQ RCU AMC
mk Bug_InsertNoExistCheck RSetUniq WSetUniq 0 0 0 NORD UNQ AMC INE
# Documented trade-offs (expected to be violated):
mk Tradeoff_DirectReadAtomic   RSetFrac  WSetFrac  0 0 0 ATOMIC
mk Tradeoff_AckOnPrepare_DirectRYW RSetRecov WSetRecov 0 0 0 AOP RYW
