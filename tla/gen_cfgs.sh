# Local eventual-index refinements. The core commit module is unchanged.
lazy_flags () {
    case "$1" in
      LazyIndex) echo 'BugSplitOutbox BugShipBeforeCommit BugForgetBeforeAck BugStaleOverwrite BugGcBeforeFloor BugFloorFromMaxAck BugNoBaseRecheck BugNoKeyRecheck BugForwardBeforeCapture BugCaptureFailOpen BugIgnoreGeneration BugAckMissingTarget' ;;
      LazyCapacity) echo 'BugNoEntryReserve BugNoByteReserve BugNoSeqReserve BugAbortLeaks' ;;
      LazyBarrier) echo 'BugLastOnly BugSkipApplyWait BugMaxAck BugWaitAfterSnapshot BugSplitFrontierView BugForgetUnresolved BugTrackOnlyWhenEnabled' ;;
      LazyHandoff) echo 'BugSourceNoFlush BugResetCounter BugDropLiveVersion BugRemovePending BugNoTargetDrain BugNoTargetFence BugNoTargetNote BugDropMarkers BugDropFloors' ;;
      LazyMeter) echo 'BugNoPrecharge BugEarlyRelease BugRefundUncertain BugMutateUnknown BugNoDrain BugNoQueueCut BugStaleInstall BugStaleCallback BugApplyCap' ;;
    esac
}
mk_lazy () {
    local name=$1 family=$2 bug=$3 flag value invariants live=FALSE e=2 b=3 q=3
    case "$family" in
      LazyIndex) invariants='TypeOK CommittedOnly DrainedConverges BaseReadSafe CandidateKeySafe' ;;
      LazyCapacity)
        invariants='TypeOK EntryPromisesFit BytePromisesFit SequencePromisesFit AbortedReleased'
        case "$bug" in
          BugNoEntryReserve) e=1; b=4; q=3 ;;
          BugNoByteReserve) e=3; b=2; q=3 ;;
          BugNoSeqReserve) e=3; b=4; q=1 ;;
        esac ;;
      LazyBarrier) invariants='TypeOK OwnWritesCovered PrefixCovered' ;;
      LazyHandoff)
        invariants='TypeOK SourceObligationsSurvive CounterContinues LiveVersionSurvives DrainedProjection'
        case "$bug" in live|BugDropLiveVersion|BugDropMarkers) live=TRUE ;; esac ;;
      LazyMeter) invariants='TypeOK ReadyEpochCurrent ReadyConservative DurableCapacity NoCapacityRefusal' ;;
    esac
    cat > "$name.cfg" <<EOF
\* generated by tla/gen_cfgs.sh
SPECIFICATION Spec
CONSTANTS
EOF
    if [ "$family" = LazyHandoff ]; then echo "  LiveBase = $live" >> "$name.cfg"; fi
    for flag in $(lazy_flags "$family"); do
        value=FALSE
        if [ "$flag" = "$bug" ]; then value=TRUE; fi
        echo "  $flag = $value" >> "$name.cfg"
    done
    if [ "$family" = LazyCapacity ]; then
        echo "  EntryLimit = $e" >> "$name.cfg"
        echo "  ByteLimit = $b" >> "$name.cfg"
        echo "  SeqLimit = $q" >> "$name.cfg"
    fi
    cat >> "$name.cfg" <<EOF
INVARIANTS $invariants
CHECK_DEADLOCK FALSE
EOF
}
for lazy_family in LazyIndex LazyCapacity LazyBarrier LazyHandoff LazyMeter; do
    mk_lazy "$lazy_family" "$lazy_family" ''
    for lazy_flag in $(lazy_flags "$lazy_family"); do
        mk_lazy "Bug_${lazy_family}${lazy_flag#Bug}" "$lazy_family" "$lazy_flag"
    done
done
